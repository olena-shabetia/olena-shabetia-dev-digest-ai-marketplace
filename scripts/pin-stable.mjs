#!/usr/bin/env node
// Generate the "stable" release channel: a second marketplace whose entries are
// pinned to release tags and commit SHAs. Claude Code has no rollback command;
// rolling back means installing from this pinned marketplace.
//
//   node scripts/pin-stable.mjs                         pin every plugin to its highest tag
//   node scripts/pin-stable.mjs sdd-engineering@1.0.0 engineering-paved-path@1.0.0 ...
//                                                       pin listed plugins to given versions
//   --out <file>   write to a file instead of stdout
//   --publish      commit the file to the `stable` branch of origin (no force push)
//
// Users then run: claude plugin marketplace add <owner>/<repo>#stable
import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const args = process.argv.slice(2);
const flag = (name) => args.includes(name);
const outIdx = args.indexOf('--out');
const out = outIdx >= 0 ? args[outIdx + 1] : null;
const pins = Object.fromEntries(
  args.filter((a) => /^[\w.-]+@\d+\.\d+\.\d+$/.test(a)).map((a) => a.split('@')),
);

const git = (...a) => execFileSync('git', a, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
const root = git('rev-parse', '--show-toplevel');
const marketplace = JSON.parse(readFileSync(join(root, '.claude-plugin', 'marketplace.json'), 'utf8'));

const remote = git('remote', 'get-url', 'origin');
const repo = remote.match(/github\.com[:/]([^/]+\/[^/.]+?)(?:\.git)?$/)?.[1];
if (!repo) { console.error(`error: origin "${remote}" is not a GitHub remote`); process.exit(1); }

const cmpVersions = (a, b) => {
  const [x, y] = [a, b].map((v) => v.split('.').map(Number));
  return x[0] - y[0] || x[1] - y[1] || x[2] - y[2];
};

const plugins = marketplace.plugins.map(({ name, source }) => {
  const versions = git('tag', '--list', `${name}--v*`).split('\n').filter(Boolean)
    .map((t) => t.slice(name.length + 3)).sort(cmpVersions);
  const version = pins[name] ?? versions.at(-1);
  if (!version || !versions.includes(version)) {
    console.error(`error: no release tag ${name}--v${version ?? '*'} (released: ${versions.join(', ') || 'none'})`);
    process.exit(1);
  }
  const tag = `${name}--v${version}`;
  return {
    name,
    source: {
      source: 'git-subdir',
      url: `https://github.com/${repo}.git`, // full HTTPS URL: the owner/repo shorthand is cloned over SSH and fails without a known host key
      path: source.replace(/^\.\//, ''),
      ref: tag,
      sha: git('rev-parse', `${tag}^{commit}`),
    },
  };
});

const stable = {
  ...marketplace,
  name: `${marketplace.name}-stable`,
  description: `Pinned stable channel of ${marketplace.name}. Generated by scripts/pin-stable.mjs, do not edit.`,
  plugins,
};
const json = `${JSON.stringify(stable, null, 2)}\n`;

if (out) writeFileSync(out, json);
if (!flag('--publish')) {
  if (!out) process.stdout.write(json);
  process.exit(0);
}

// Publish to the `stable` branch as a normal commit, preserving history.
const work = mkdtempSync(join(tmpdir(), 'stable-'));
const inWork = (...a) => execFileSync('git', a, { cwd: work, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
const exists = git('ls-remote', '--heads', 'origin', 'stable') !== '';
if (exists) execFileSync('git', ['clone', '--quiet', '--branch', 'stable', '--depth', '1', remote, work]);
else { inWork('init', '--quiet', '--initial-branch', 'stable'); inWork('remote', 'add', 'origin', remote); }
mkdirSync(join(work, '.claude-plugin'), { recursive: true });
writeFileSync(join(work, '.claude-plugin', 'marketplace.json'), json);
inWork('add', '-A');
if (inWork('status', '--porcelain') === '') { console.log('stable branch is already up to date'); process.exit(0); }
const summary = plugins.map((p) => p.source.ref).join(', ');
inWork('commit', '--quiet', '-m', `Pin stable channel: ${summary}`);
inWork('push', 'origin', 'stable');
console.log(`Published stable channel (${summary}). Users add it with: claude plugin marketplace add ${repo}#stable`);
